import re
import sys
from pathlib import Path

__all__ = ["apply"]

pattern_indenter = re.compile(r"^([^\n])", flags=re.MULTILINE)
pattern_indented = re.compile(r"^( *)\$\{(.*?)\}$", flags=re.MULTILINE)
pattern_unindented = re.compile(r"\$\{(.*?)\}")


class Templater:
    def __init__(self, vars: dict[str, str]) -> None:
        self.vars = vars

    def indented(self, match: re.Match[str]) -> str:
        indent = len(match.group(1))
        code = self.vars[match.group(2)].strip()
        return pattern_indenter.sub(rf"{" " * indent}\1", code)

    def unindented(self, match: re.Match[str]) -> str:
        return self.vars[match.group(1)]


def apply(path: Path) -> None:
    frame = sys._getframe(1)  # pyright: ignore[reportPrivateUsage] # ruff: ignore[private-member-access]
    vars = frame.f_globals
    del frame
    templater = Templater(vars)
    template_path = path.parent / (path.name + ".in")
    code = template_path.read_text("utf-8")
    code = pattern_indented.sub(templater.indented, code)
    code = pattern_unindented.sub(templater.unindented, code)
    path.write_text(f"""# This file was automatically generated from {template_path}
# Do NOT edit this file manually

{code}""", "utf-8")
